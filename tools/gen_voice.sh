#!/bin/bash
# 火焰山 · 牛魔 — render the spoken lines with macOS `say` (offline) into assets/audio/voice/<id>.m4a, plus
# voice.json (id, speaker, text, duration in seconds of the file as rendered).
#
#   tools/gen_voice.sh            render every line
#   tools/gen_voice.sh b1 m2      render only these ids (the manifest is always rebuilt from every file present)
#
# 牛魔王: the zh_CN "Grandpa" voice, pitch base pushed far down ([[pbas]]), slow ([[rate]]). The game slows it again
#         (playbackRate ~0.84: an octave-ish lower, huge) and puts it through a low-pass and a cavern reverb.
# 孙悟空: the zh_CN "Eddy" voice, pitch base up, wider pitch modulation, quick.
# The manifest durations are those of the files; the game divides by its playbackRate.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=assets/audio/voice
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"

BULL_VOICE='Grandpa (中文（中国大陆）)'
MONKEY_VOICE='Eddy (中文（中国大陆）)'
BULL_FX='[[pbas 26]][[pmod 30]][[rate 150]]'
MONKEY_FX='[[pbas 54]][[pmod 80]][[rate 225]]'

# id | speaker (bull|monkey) | subtitle text | spoken text (embedded [[slnc ms]] = a held breath)
LINES=$(cat <<'EOF'
b1|bull|……五百年。压在山下的七弟，也爬出来了。|五百年。[[slnc 300]]压在山下的七弟，也爬出来了。
m1|monkey|平天大圣好定力。一坐千年，连火都坐倦了。|平天大圣，好定力。[[slnc 120]]一坐千年，连火都坐倦了。
b2|bull|又来借扇？上回钻我妻的肚子——这回，钻哪儿？|又来借扇？[[slnc 200]]上回钻我妻的肚子，[[slnc 200]]这回，钻哪儿？
m2|monkey|这回不借。来拿。|这回不借。[[slnc 350]]来拿。
b3|bull|红孩儿的账，铁扇的账……今日一并算。|红孩儿的账，铁扇的账，[[slnc 250]]今日，一并算。
m3|monkey|正好。俺老孙压了五百年，骨头正痒。|正好。[[slnc 100]]俺老孙压了五百年，骨头正痒。
p1|bull|坐了一千年……也该站起来，看看这天了。|坐了一千年，[[slnc 300]]也该站起来，看看这天了。
p2|monkey|站起来好。倒下去，才响。|站起来好。[[slnc 250]]倒下去，才响。
e1|monkey|大哥……下雨了。|大哥，[[slnc 600]]下雨了。
EOF
)

want=" $* "
while IFS='|' read -r id who sub spoken; do
  [ -z "$id" ] && continue
  if [ $# -gt 0 ] && [[ "$want" != *" $id "* ]]; then continue; fi
  if [ "$who" = bull ]; then v=$BULL_VOICE; fx=$BULL_FX; else v=$MONKEY_VOICE; fx=$MONKEY_FX; fi
  say -v "$v" -o "$TMP/$id.aiff" "$fx$spoken"
  afconvert -f m4af -d aac "$TMP/$id.aiff" "$OUT/$id.m4a"
  echo "  $id  $who  $(afinfo "$OUT/$id.m4a" | awk '/estimated duration/ {print $3}') s  $sub"
done <<< "$LINES"

# the manifest (every line that has a file)
{
  echo '{'
  echo '  "note": "generated by tools/gen_voice.sh (macOS say); durations are of the files, before the game'"'"'s playbackRate",'
  echo '  "lines": {'
  first=1
  while IFS='|' read -r id who sub spoken; do
    [ -z "$id" ] && continue
    [ -f "$OUT/$id.m4a" ] || continue
    d=$(afinfo "$OUT/$id.m4a" | awk '/estimated duration/ {printf "%.3f", $3}')
    [ $first = 1 ] || echo ','
    first=0
    printf '    "%s": { "speaker": "%s", "text": "%s", "file": "%s.m4a", "duration": %s }' "$id" "$who" "$sub" "$id" "$d"
  done <<< "$LINES"
  echo
  echo '  }'
  echo '}'
} > "$OUT/voice.json"
echo "wrote $OUT/voice.json"
